from __future__ import annotations

import argparse
import importlib
import json
import sys
from pathlib import Path


def key_for_finding(finding) -> str:
    ref = finding.ref
    return f"{ref.object_type.value}|{ref.table}|{ref.name}"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("analyzer_root", help="Folder containing run_analyzer.py and pbi_usage_analyzer/")
    parser.add_argument("suite_root", help="Folder generated by generate_validation_suite.py")
    args = parser.parse_args()

    analyzer_root = Path(args.analyzer_root).resolve()
    suite_root = Path(args.suite_root).resolve()

    sys.path.insert(0, str(analyzer_root))

    from pbi_usage_analyzer.discovery import discover_project
    from pbi_usage_analyzer.analysis.build_graph import build_graph
    from pbi_usage_analyzer.analysis.classify import classify

    scenarios = sorted(p for p in suite_root.iterdir() if p.is_dir() and (p / "expected.json").exists())
    failures = 0
    checks = 0

    print("=" * 78)
    print("POWER BI ANALYZER SYNTHETIC VALIDATION")
    print("=" * 78)

    for scenario in scenarios:
        expected_doc = json.loads((scenario / "expected.json").read_text(encoding="utf-8"))
        expected = expected_doc["expected_status"]

        project = discover_project(scenario)
        ctx = build_graph(project.report_folder, project.model_folder)
        findings = classify(ctx.graph)
        actual = {key_for_finding(f): f.status.value for f in findings}

        scenario_failures = []
        for key, wanted in expected.items():
            checks += 1
            got = actual.get(key)
            if got != wanted:
                scenario_failures.append((key, wanted, got))

        if scenario_failures:
            failures += len(scenario_failures)
            print(f"\n[FAIL] {scenario.name}")
            for key, wanted, got in scenario_failures:
                print(f"  {key}")
                print(f"    expected: {wanted}")
                print(f"    actual:   {got}")
        else:
            print(f"\n[PASS] {scenario.name}")

    print("\n" + "-" * 78)
    print(f"Checks:   {checks}")
    print(f"Failures: {failures}")
    print(f"Result:   {'PASS' if failures == 0 else 'FAIL'}")

    if failures:
        sys.exit(1)


if __name__ == "__main__":
    main()
